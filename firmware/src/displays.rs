//! 4 SH1106 OLED Display Controller over SPI1 with Chip-Select Multiplexing
//!
//! Accepts 1BPP raw pixel chunks (1,024 bytes per display = 4 chunks of 256 bytes)
//! pre-formatted in SH1106's native Page Addressing layout (1 byte = 8 vertical pixels).

use stm32f4xx_hal::{
    gpio::{Output, PushPull, PA5, PA7, PB0, PB1, PB10, PB2, PC15},
    pac::SPI1,
    prelude::*,
    rcc::Clocks,
    spi::{Mode, NoMiso, Phase, Polarity, Spi},
};

type SpiType = Spi<SPI1>;

const SH1106_INIT: &[u8] = &[
    0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0x8D, 0x14, 0x20, 0x02, 0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xCF, 0xD9,
    0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF,
];

pub struct DisplaySystem {
    spi: SpiType,
    dc: PC15<Output<PushPull>>,
    cs0: PB0<Output<PushPull>>,
    cs1: PB1<Output<PushPull>>,
    cs2: PB2<Output<PushPull>>,
    cs3: PB10<Output<PushPull>>,

    // Raw 1BPP pixel buffers for each of the 4 displays (1024 bytes each)
    pixel_buffers: [[u8; 1024]; 4],
    dirty: [bool; 4],
}

impl DisplaySystem {
    pub fn new(
        spi1: SPI1,
        sck: PA5,
        mosi: PA7,
        mut dc: PC15<Output<PushPull>>,
        mut cs0: PB0<Output<PushPull>>,
        mut cs1: PB1<Output<PushPull>>,
        mut cs2: PB2<Output<PushPull>>,
        mut cs3: PB10<Output<PushPull>>,
        clocks: &Clocks,
    ) -> Self {
        cs0.set_high();
        cs1.set_high();
        cs2.set_high();
        cs3.set_high();

        let sck_alt = sck.into_alternate();
        let mosi_alt = mosi.into_alternate();

        let spi_mode = Mode { polarity: Polarity::IdleLow, phase: Phase::CaptureOnFirstTransition };

        let mut spi = Spi::new(spi1, (sck_alt, NoMiso::new(), mosi_alt), spi_mode, 8.MHz(), clocks);

        // Initialize all displays simultaneously
        cs0.set_low();
        cs1.set_low();
        cs2.set_low();
        cs3.set_low();

        dc.set_low(); // Command mode
        let _ = spi.write(SH1106_INIT);

        cs0.set_high();
        cs1.set_high();
        cs2.set_high();
        cs3.set_high();

        let mut sys = Self { spi, dc, cs0, cs1, cs2, cs3, pixel_buffers: [[0u8; 1024]; 4], dirty: [true; 4] };

        // Render splash screen on display 0
        sys.pixel_buffers[0].copy_from_slice(&SPLASH_DATA);

        sys
    }

    /// Set a 256-byte 1BPP pixel chunk (chunk 0..3) for a display (0..3)
    pub fn set_pixel_chunk(&mut self, display_id: u8, chunk_id: u8, pixels: &[u8; 256]) {
        let disp = (display_id & 0x03) as usize;
        let chunk = (chunk_id & 0x03) as usize;
        let start = chunk * 256;
        self.pixel_buffers[disp][start..start + 256].copy_from_slice(pixels);
        self.dirty[disp] = true;
    }

    /// Flush any dirty displays to hardware
    pub fn update(&mut self) {
        for i in 0..4 {
            if !self.dirty[i] {
                continue;
            }
            self.dirty[i] = false;

            match i {
                0 => {
                    self.cs0.set_low();
                }
                1 => {
                    self.cs1.set_low();
                }
                2 => {
                    self.cs2.set_low();
                }
                3 => {
                    self.cs3.set_low();
                }
                _ => {}
            };

            for page in 0..8 {
                // Set Page and Column (SH1106 requires col offset of 2)
                self.dc.set_low();
                let _ = self.spi.write(&[0xB0 | page as u8, 0x02, 0x10]);

                // Write 128 bytes of page data
                self.dc.set_high();
                let start = page * 128;
                let _ = self.spi.write(&self.pixel_buffers[i][start..start + 128]);
            }

            match i {
                0 => {
                    self.cs0.set_high();
                }
                1 => {
                    self.cs1.set_high();
                }
                2 => {
                    self.cs2.set_high();
                }
                3 => {
                    self.cs3.set_high();
                }
                _ => {}
            };
        }
    }
}

